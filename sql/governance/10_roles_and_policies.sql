ALTER TABLE RAW.FACT_MARKETING_LEADS      ADD ROW ACCESS POLICY ANALYTICS.MVN_STATE_ROW_ACCESS_POLICY ON (state);


-- =============================================================================
-- 4. DYNAMIC DATA MASKING POLICIES (DIM_CUSTOMER.EMAIL & DIM_CUSTOMER.PHONE)
-- =============================================================================

CREATE OR REPLACE MASKING POLICY ANALYTICS.MVN_EMAIL_MASKING_POLICY
AS (val VARCHAR) RETURNS VARCHAR ->
    CASE
        WHEN CURRENT_ROLE() = 'MVN_AZ_STORE_MGR_ROLE' THEN '***MASKED***@' || SPLIT_PART(val, '@', 2)
        WHEN CURRENT_ROLE() IN ('MVN_EXEC_ROLE', 'ACCOUNTADMIN', 'SYSADMIN') THEN val
        ELSE '***MASKED***@' || SPLIT_PART(val, '@', 2)
    END
COMMENT = 'Masks customer email local-part for MVN_AZ_STORE_MGR_ROLE; clear text for MVN_EXEC_ROLE';

CREATE OR REPLACE MASKING POLICY ANALYTICS.MVN_PHONE_MASKING_POLICY
AS (val VARCHAR) RETURNS VARCHAR ->
    CASE
        WHEN CURRENT_ROLE() = 'MVN_AZ_STORE_MGR_ROLE' THEN '(***) ***-' || RIGHT(val, 4)
        WHEN CURRENT_ROLE() IN ('MVN_EXEC_ROLE', 'ACCOUNTADMIN', 'SYSADMIN') THEN val
        ELSE '(***) ***-' || RIGHT(val, 4)
    END
COMMENT = 'Masks customer phone prefix for MVN_AZ_STORE_MGR_ROLE; clear text for MVN_EXEC_ROLE';

ALTER TABLE RAW.DIM_CUSTOMER MODIFY COLUMN email SET MASKING POLICY ANALYTICS.MVN_EMAIL_MASKING_POLICY;
ALTER TABLE RAW.DIM_CUSTOMER MODIFY COLUMN phone SET MASKING POLICY ANALYTICS.MVN_PHONE_MASKING_POLICY;


