-- =============================================================================
-- 3. ROW ACCESS POLICY (STATE-LEVEL SECURITY FOR STORE MANAGERS)
-- =============================================================================

CREATE OR REPLACE ROW ACCESS POLICY ANALYTICS.MVN_STATE_ROW_ACCESS_POLICY
AS (row_state VARCHAR) RETURNS BOOLEAN ->
    CASE
        -- Evaluate primary session role first so live role switching is deterministic
        WHEN CURRENT_ROLE() = 'MVN_AZ_STORE_MGR_ROLE' THEN (row_state = 'AZ')
        WHEN CURRENT_ROLE() IN ('MVN_EXEC_ROLE', 'ACCOUNTADMIN', 'SYSADMIN') THEN TRUE
        WHEN IS_ROLE_IN_SESSION('MVN_AZ_STORE_MGR_ROLE')
             AND NOT IS_ROLE_IN_SESSION('MVN_EXEC_ROLE') THEN (row_state = 'AZ')
        ELSE TRUE
    END
COMMENT = 'Restricts MVN_AZ_STORE_MGR_ROLE to state = AZ across all location-keyed facts and dimensions; full visibility for MVN_EXEC_ROLE';

-- Attach Row Access Policy to location dimension and all location-keyed fact tables
ALTER TABLE RAW.DIM_LOCATION              ADD ROW ACCESS POLICY ANALYTICS.MVN_STATE_ROW_ACCESS_POLICY ON (state);
ALTER TABLE RAW.FACT_SALES_DAILY_LOCATION ADD ROW ACCESS POLICY ANALYTICS.MVN_STATE_ROW_ACCESS_POLICY ON (state);
ALTER TABLE RAW.FACT_SALES_TRANSACTION    ADD ROW ACCESS POLICY ANALYTICS.MVN_STATE_ROW_ACCESS_POLICY ON (state);
ALTER TABLE RAW.FACT_SALES_LINE           ADD ROW ACCESS POLICY ANALYTICS.MVN_STATE_ROW_ACCESS_POLICY ON (state);
ALTER TABLE RAW.FACT_PLANTED_JOBS         ADD ROW ACCESS POLICY ANALYTICS.MVN_STATE_ROW_ACCESS_POLICY ON (state);
ALTER TABLE RAW.FACT_INVENTORY_DAILY      ADD ROW ACCESS POLICY ANALYTICS.MVN_STATE_ROW_ACCESS_POLICY ON (state);
